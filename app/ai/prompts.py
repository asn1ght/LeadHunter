def quality_user(
    url: str, niche: str, title: str | None, description: str | None, h1: list[str],
    issues: list[dict[str, Any]], text: str,
) -> str:
    tech = "\n".join(f"- {i.get('title')}" for i in issues) or "- явных технических проблем нет"
    return (
        f"Ниша: {niche}\nURL: {url}\nTitle: {title or '—'}\nDescription: {description or '—'}\n"
        f"H1: {json.dumps(h1, ensure_ascii=False)}\n\nТехнические проблемы (найдены скриптом):\n{tech}\n\n"
        f"Текст главной страницы (обрезан):\n\"\"\"\n{text[:7000]}\n\"\"\"\n\nВерни json."
    )


