def letter_user(
    channel: str, company: str, domain: str, problems: list[str], pitch: str | None,
    owner: dict[str, str], shorter: bool = False, previous: str | None = None,
) -> str:
    ch = "email (можно приветствие «Здравствуйте!»)" if channel == "email" else "мессенджер (ещё короче и проще, 2–4 предложения)"
    sign = "\n".join(v for v in (owner.get("name"), owner.get("phone"), owner.get("telegram"), owner.get("email")) if v)
    parts = [
        f"Канал: {ch}",
        f"Компания: {company} ({domain})",
        "Проблемы сайта из аудита:\n" + "\n".join(f"- {p}" for p in problems[:6]),
    ]
    if pitch:
        parts.append(f"Главный крючок: {pitch}")
    parts.append(f"Подпись:\n{sign or '(без подписи)'}")
    if previous:
        parts.append(f"Предыдущий вариант (напиши {'короче, до 350 знаков' if shorter else 'другой вариант, с другим заходом'}):\n{previous}")
    return "\n\n".join(parts)
